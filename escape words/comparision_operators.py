a = 10
b = 20
print("Equal to (==):", a == b) # Equal to operator checks if a is equal to b
print("Not equal to (!=):", a != b) # Not equal to operator checks if a is not equal to b
print("Greater than (>):", a > b) # Greater than operator checks if a is greater than b
print("Less than (<):", a < b) # Less than operator checks if a is less than b
print("Greater than or equal to (>=):", a >= b) # Greater than or equal to operator checks if a is greater than or equal to b
print("Less than or equal to (<=):", a <= b) # Less than or equal to operator checks if a is less than or equal to b    
